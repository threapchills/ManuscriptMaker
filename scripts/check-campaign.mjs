import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const base = process.env.BASE_URL || 'http://localhost:5173/ManuscriptMaker/';
await mkdir('.local', { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME || undefined });
const context = await browser.newContext({ viewport: { width: 1360, height: 900 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const setSelected = async (label, value) => {
  const input = page.getByRole('spinbutton', { name: label });
  await input.fill(String(value));
  await input.blur();
};
try {
  await page.goto(base);
  await page.screenshot({ path: '.local/campaign-first-screen.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('button', { name: 'Start a playable game' })).toBeVisible();
  assert.ok(await page.evaluate(() => document.body.scrollWidth) <= 390);
  await page.screenshot({ path: '.local/campaign-first-screen-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1360, height: 900 });
  await page.getByRole('button', { name: 'Start a playable game' }).click();
  await expect(page.getByRole('heading', { name: 'Who will cross these pages?' })).toBeVisible();
  await page.screenshot({ path: '.local/campaign-character-choice.png', fullPage: true });
  await page.getByRole('button', { name: /Make new character/ }).click();
  await page.waitForFunction(() => Array.from(document.querySelectorAll('.character-page img')).every(image => image.complete && image.naturalWidth > 0));
  await page.screenshot({ path: '.local/campaign-character-maker.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole('button', { name: 'Begin with this character' })).toBeVisible();
  await page.screenshot({ path: '.local/campaign-character-maker-mobile.png', fullPage: true });
  await page.setViewportSize({ width: 1360, height: 900 });
  await page.getByRole('button', { name: 'Fox head' }).click();
  await page.getByRole('button', { name: 'Body' }).click();
  await page.getByRole('button', { name: 'Red tunic' }).click();
  await page.getByRole('button', { name: 'Legs' }).click();
  await page.getByRole('button', { name: 'Red trousers' }).click();
  await page.getByRole('button', { name: 'Begin with this character' }).click();
  await expect(page.getByText('Practice page 1 of 2')).toBeVisible();
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('manuscript-maker:campaign-v01')));
  const progress = await page.evaluate(() => JSON.parse(localStorage.getItem('manuscript-maker:campaign-progress-v01')));
  assert.equal(saved.pages.length, 2);
  assert.ok(saved.pages.every(folio => folio.layers.some(layer => layer.gameRole === 'player' && layer.src.startsWith('data:image/png;base64,'))));
  assert.equal(progress.character.parts.Head, 'char-head-fox');
  assert.equal(progress.unlockedIndex, 0);
  await expect(page.getByRole('button', { name: 'Next page' })).toBeDisabled();
  await expect(page.getByTitle(/Add Short meadow ground/)).toBeVisible();
  await expect(page.getByTitle(/Add Stone cottage/)).toHaveCount(0);
  await page.screenshot({ path: '.local/campaign-custom.png', fullPage: true });

  // Collision follows the painted pixels, so pieces must meet where they visibly meet.
  await page.getByTitle(/Add Short meadow ground/).click();
  await setSelected('X position', 380);
  await setSelected('Y position', 590);
  await setSelected('Width', 170);
  await page.getByTitle(/Add Wooden bridge/).click();
  await setSelected('X position', 530);
  await setSelected('Y position', 530); // deck level with the grass, railings above it
  await setSelected('Width', 270);
  await page.getByRole('button', { name: 'Play page' }).click();
  await page.waitForFunction(() => !!window.__playSession);
  await page.keyboard.down('ArrowRight');
  // Leap the last gap from the end of the bridge.
  await page.waitForFunction(() => { const s = window.__playSession; return s && (s.world.body.x + s.world.body.w / 2) * s.spec.field.cell > 770; }, null, { timeout: 9000 });
  await page.keyboard.down('Space'); await page.waitForTimeout(260); await page.keyboard.up('Space');
  await expect(page.getByText('Page complete')).toBeVisible({ timeout: 9000 });
  await page.keyboard.up('ArrowRight');
  await page.screenshot({ path: '.local/campaign-win.png', fullPage: true });
  await page.getByRole('button', { name: 'Turn the page →' }).click();
  await expect(page.getByText('Practice page 2 of 2')).toBeVisible();
  await expect(page.getByTitle(/Add Stone cottage/)).toBeVisible();
  const unlocked = await page.evaluate(() => JSON.parse(localStorage.getItem('manuscript-maker:campaign-progress-v01')));
  assert.equal(unlocked.unlockedIndex, 1);
  await page.getByRole('button', { name: 'Manuscript sandbox' }).click();
  await expect(page.getByRole('button', { name: 'Campaign game' })).toBeVisible();
  await page.getByRole('button', { name: 'Campaign game' }).click();
  await expect(page.getByText('Practice page 2 of 2')).toBeVisible();
  await page.reload();
  await expect(page.getByText('Practice page 2 of 2')).toBeVisible();
  await page.getByRole('button', { name: 'New game' }).click();
  await page.getByRole('button', { name: 'The watchful hare', exact: true }).click();
  await expect(page.getByText('Practice page 1 of 2')).toBeVisible();
  await page.getByRole('button', { name: 'New game' }).click();
  await page.getByRole('button', { name: 'Restore previous game' }).click();
  await expect(page.getByText('Practice page 2 of 2')).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.body.scrollWidth) <= 390);
  assert.deepEqual(errors, []);
  console.log('PASS custom character, curated pieces, route construction, checkpoint gate, page turn, mode resume, previous-game restore, mobile fit');
} finally { await browser.close(); }
